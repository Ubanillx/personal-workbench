-- 012_webdav_url_from_env.sql
-- WebDAV 的**地址**从「每个账号一份」改成「部署级一份」（D-44）。
--
-- 背景：D-43 把整份 WebDAV 配置做成了按账号保存，理由是「不同的人可能用不同的
-- NAS 与账号」。实际上一个团队通常**共用同一个 NAS**，地址没必要每人填一遍；
-- 于是地址改成从环境变量 `WEBDAV_URL` 读（例如 http://192.168.0.242:5005），
-- 而用户名 / 密码 / 浏览根目录 / 超时仍然是每个账号自己的，继续在
-- `/settings?tab=webdav` 里维护。
--
-- 约定：
-- 1. `webdav_settings.url` 不再被任何代码读取或写入，这里删掉它——留着一个
--    「看起来还能配地址」的死列，比删掉更容易误导后来的人；
-- 2. 这一步会丢弃以前按账号保存过的地址。迁移前的库有自动备份（见 db/client.ts），
--    真要找回旧值可以从备份里读；如果以前填的不是同一个 NAS，把那个地址写进
--    `.env` 的 WEBDAV_URL 即可；
-- 3. **一行仍然代表「这个账号登记过自己的凭据」**：没有行 = 未接入，页面隐藏远端
--    入口、接口返回 503。也就是说地址配好了也不会自动对所有人开放——
--    每个人都要在设置页里保存一次自己的账号（NAS 允许匿名访问就留空保存）。
ALTER TABLE webdav_settings DROP COLUMN url;
